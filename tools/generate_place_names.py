#!/usr/bin/env python3
"""Generate the offline lookup from the checked-in JMA dictionary snapshot.

To update: download the source URL recorded in data/jma_epicenters.json,
extract each entry's japanese/english fields into names, update retrieved,
then run this script. No network access is used during a firmware build.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / "data/jma_epicenters.json").read_text())
names = data["names"]
assert names and all(jp and en for jp, en in names.items())
quote = lambda value: json.dumps(value, ensure_ascii=False)
# JMA's web dictionary contains invisible zero-width spaces in a few labels.
# Remove those web formatting artifacts; preserve all geographic wording.
rows = "\n".join(f"  {{{quote(jp)}, {quote(en.replace(chr(0x200b), ''))}}}," for jp, en in sorted(names.items()))
header = f'''#pragma once
#include <string.h>

// Generated by tools/generate_place_names.py; edit the source snapshot instead.
// Source: {data["source"]}
// Retrieved: {data["retrieved"]}. Exact JMA names; no inferred translations.
struct QuakePlaceName {{ const char* jp; const char* en; }};
static const QuakePlaceName QUAKE_PLACE_NAMES[] = {{
{rows}
}};

// Empty result means the caller must retain the original Japanese name.
inline const char* quakePlaceEnglish(const char* jp) {{
  if (!jp) return "";
  for (const auto& name : QUAKE_PLACE_NAMES) {{
    if (strcmp(jp, name.jp) == 0) return name.en;
  }}
  return "";
}}
'''
(ROOT / "place_names.h").write_text(header)
